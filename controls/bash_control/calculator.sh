#!/bin/bash
# калькулятор
read -p "Введите первое число: " a
read -p "Введите второе число: " b
read -p "Введите операцию (+, -, *, /): " op

if ! [[ "$a" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: \"$a\" не является целым числом"
    exit 1
fi

if ! [[ "$b" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: \"$b\" не является целым числом"
    exit 1
fi

case "$op" in
    +)
        echo "Результат: $a + $b = $((a + b))"
        ;;
    -)
        echo "Результат: $a - $b = $((a - b))"
        ;;
    \*)
        echo "Результат: $a * $b = $((a * b))"
        ;;
    /)
        if [ "$b" -eq 0 ]; then
            echo "Ошибка: деление на ноль"
            exit 1
        fi
        echo "Результат: $a / $b = $((a / b))"
        ;;
    *)
        echo "Ошибка: неизвестная операция \"$op\""
        exit 1
        ;;
esac
