#!/bin/bash
# Считаем сумму чисел от 1 до N

read -p "Введите N: " n

prod=1                  # задание 7: произведение (факториал)
sum=0                    # начальное значение счётчика
i=1                      # счётчик цикла

# while — цикл «пока условие истинно»
# [ $i -le $n ] — «i меньше или равно n»
while [ "$i" -le "$n" ]; do
    sum=$((sum + i))
    prod=$((prod * i))     # добавляем i к сумме
    i=$((i + 1))         # увеличиваем i на 1
done

echo "Сумма чисел от 1 до $n = $sum"
echo "Произведение чисел от 1 до $n = $prod"
